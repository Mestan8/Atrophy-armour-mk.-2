"""Write docs/evidence_matrix.md from the evidence catalog.

Run ``python build_evidence_matrix.py`` after changing anything in data/evidence.
A test fails if the committed matrix no longer matches the catalog.
"""

from pathlib import Path

from evidence_catalog import CATEGORIES, catalog, study_label
from study_library import STUDIES


MATRIX_PATH = Path(__file__).resolve().parent / "docs" / "evidence_matrix.md"


def _cell(study_id: str, category: str) -> str:
    items = [item for item in catalog() if item.study_id == study_id and item.outcome_category == category]
    if not items:
        return "not measured"
    outcomes = len({item.outcome_id for item in items})
    ns = sorted({item.n for item in items if item.n is not None})
    counts = sorted({item.n_counts.split(" (")[0] for item in items})
    statistics = sorted({f"{item.statistic_type.split(' (')[0]} ± {item.dispersion_type}" for item in items})
    timepoints = sorted({item.timepoint.split(" (")[0] for item in items if item.timepoint_kind == "postflight"})
    n_text = (
        f"n {ns[0]}" if len(ns) == 1 else f"n {ns[0]}–{ns[-1]}" if ns else "n not reported"
    )
    return (
        f"{len(items)} values, {outcomes} outcomes; {n_text} ({', '.join(counts)}); "
        f"{'; '.join(statistics)}; postflight: {', '.join(timepoints)}"
    ).replace("|", "/")


def _recovery(study_id: str) -> str:
    items = [item for item in catalog() if item.study_id == study_id and item.recovery_day is not None]
    by_outcome: dict[str, set[float]] = {}
    for item in items:
        by_outcome.setdefault(item.outcome_id, set()).add(item.recovery_day)
    repeated = {key: days for key, days in by_outcome.items() if len(days) > 1}
    if not repeated:
        return "not measured (one postflight timepoint per outcome)"
    days = sorted({day for values in repeated.values() for day in values})
    return f"{len(repeated)} outcomes at several days; R+ days used: " + ", ".join(
        f"{day:g}" for day in days
    )


def render() -> str:
    lines = [
        "# Evidence matrix",
        "",
        "Generated by `build_evidence_matrix.py` from `data/evidence/*.json`; do not edit by hand.",
        "",
        "Each cell lists what the catalog holds for a study and category: the number of",
        "stored values and outcomes, the sample size and what it counts, the statistic and",
        "its dispersion, and the postflight timepoints. \"not measured\" means the study (or,",
        "for Gopalakrishnan et al. 2010, its abstract) reports nothing in that category.",
        "Recovery day positions for windows (for example \"within two weeks\") are nominal; see each record.",
        "",
        "| Study | " + " | ".join(CATEGORIES.values()) + " | Recovery |",
        "|---|" + "---|" * (len(CATEGORIES) + 1),
    ]
    for study in STUDIES:
        study_id = str(study["id"])
        name = study_label(study_id)
        if study["source_availability"] == "abstract_only":
            name += " (abstract only)"
        cells = [_cell(study_id, category) for category in CATEGORIES]
        lines.append(f"| {name} | " + " | ".join(cells) + f" | {_recovery(study_id)} |")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    MATRIX_PATH.parent.mkdir(exist_ok=True)
    MATRIX_PATH.write_text(render(), encoding="utf-8")
    print(f"Wrote {MATRIX_PATH}")
